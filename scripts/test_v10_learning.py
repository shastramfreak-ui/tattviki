from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def ok(label,condition):
 if not condition:raise AssertionError(label)
 checks.append(label);print('PASS',label,flush=True)
SCRIPTS=['content','curriculum','deepdives','enterprise_curriculum','learning-guides','enterprise_cases','studio-templates','studio-graph','studio','advanced','semantic-workbench','app']
def load(page,storage=None):
 page.set_content('<!doctype html><html><head><meta name="theme-color" content="#101b2b" /></head><body><div id="app"></div></body></html>')
 page.evaluate('''(data)=>{const items=data||{};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>items[k]??null,setItem:(k,v)=>items[k]=String(v),removeItem:k=>delete items[k]}});Object.defineProperty(window,'sessionStorage',{configurable:true,value:{getItem:k=>items[k]??null,setItem:(k,v)=>items[k]=String(v),removeItem:k=>delete items[k]}})}''',storage or {})
 for f in ['styles.css','theme-v9.css','learning-v10.css']:page.add_style_tag(content=(ROOT/'assets'/f).read_text())
 for f in SCRIPTS:page.add_script_tag(content=(ROOT/'assets'/f'{f}.js').read_text())
def go(page,loc):
 page.evaluate('(v)=>location.hash="#"+v',loc);page.wait_for_timeout(50)
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 ctx=browser.new_context(viewport={'width':1440,'height':940},accept_downloads=True)
 page=ctx.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 load(page)
 ok('613 study guides load',page.evaluate('Object.keys(window.TATTVIKI_GUIDES).length')==613)
 ok('home starts at 0 lessons',page.get_by_text('0 / 613',exact=True).count()>=1)
 go(page,'lesson/rdf-triples')
 ok('detailed article sections',page.locator('.chapter-section').count()==5)
 ok('technical explanation and real RDF pattern',page.get_by_text('RDF is a graph of statements',exact=False).count()>=1 and page.locator('.chapter-section pre').count()==1)
 ok('reflection and implementation checks',page.get_by_text('What to test before you move on').count()==1)
 ok('time separates reading and practice','reading +' in page.locator('.page').inner_text())
 correct=page.evaluate("(()=>{let l=window.OT.lessons.find(l=>l.id==='rdf-triples');return l.quiz.answer;})()")
 page.locator(f'[data-action="quiz"][data-answer="{(correct+1)%3}"]').click()
 ok('wrong answer does not count',page.locator('.completion-pill').inner_text().startswith('Answer correctly'))
 page.locator(f'[data-action="quiz"][data-answer="{correct}"]').click()
 ok('correct answer automatically completes',page.locator('.completion-pill').inner_text().startswith('✓ Completed'))
 go(page,'home')
 ok('dashboard reports 1 / 613',page.get_by_text('1 / 613',exact=True).count()>0)
 saved=page.evaluate('localStorage.getItem("tattviki-completed")')
 fresh=browser.new_page();load(fresh,{'tattviki-completed':saved})
 ok('completion survives simulated reload and reinitialization',fresh.get_by_text('1 / 613',exact=True).count()>0)
 go(page,'lesson/course-12-18')
 ok('generated lesson gets detailed technical guide',page.locator('.chapter-section').count()==5)
 question=page.locator('.quiz h3').inner_text()
 ok('question no longer generic placeholder',not question.startswith('When implementing'))
 ci=page.evaluate("(()=>{let g=window.TATTVIKI_GUIDES['course-12-18'];let buttons=[...document.querySelectorAll('[data-action=quiz]')];return buttons.findIndex(b=>b.innerText.includes(g.review.a));})()")
 ok('topic quiz has a clear correct option',ci>=0)
 page.locator(f'[data-action="quiz"][data-answer="{ci}"]').click()
 go(page,'home')
 ok('homepage increases to 2/613',page.get_by_text('2 / 613',exact=True).count()>0)
 go(page,'learn')
 with page.expect_download() as out:page.locator('[data-action="export-progress"]').click()
 dl=out.value; f=ROOT/'previews/v10-progress-backup.json';dl.save_as(f)
 payload=json.loads(f.read_text())
 ok('export backup has correct completion list',len(payload['completed'])==2 and payload['format']=='tattviki-progress')
 other=browser.new_page();load(other)
 go(other,'learn')
 ok('fresh browser has no inherited completion',other.get_by_text('0 / 613',exact=False).count()>0)
 with other.expect_file_chooser() as chooser:other.locator('[data-action="restore-progress"]').click()
 chooser.value.set_files(str(f));other.wait_for_timeout(200)
 ok('backup restore imports completed lessons',other.get_by_text('2 / 613',exact=False).count()>0)
 old=browser.new_page();load(old,{'tattviki-completed':json.dumps(['what-is-kg','turtle','unknown-removed-lesson'])})
 ok('legacy saved completions retained and stale IDs excluded',old.get_by_text('2 / 613',exact=True).count()>0)
 go(page,'lesson/ent-01-00')
 ok('enterprise metadata lesson expanded',page.locator('.chapter-section').count()==5)
 page.screenshot(path=str(ROOT/'previews/v10-deep-lesson.png'),full_page=True)
 go(page,'learn');page.screenshot(path=str(ROOT/'previews/v10-learning-progress.png'),full_page=True)
 ok('no browser runtime errors',not errors)
 browser.close()
print(json.dumps({'passed':len(checks),'checks':checks,'runtimeErrors':errors},indent=2))
